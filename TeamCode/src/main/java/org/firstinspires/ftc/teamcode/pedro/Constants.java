package org.firstinspires.ftc.teamcode.pedro;

import com.pedropathing.algorithm.Foresight;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.controllers.Controller;
import com.pedropathing.follower.Follower;
import com.pedropathing.math.Matrix;
import com.pedropathing.math.Vector2D;
import com.pedropathing.revhub.drivetrains.Mecanum;
import com.pedropathing.revhub.drivetrains.MecanumConfig;
import com.pedropathing.revhub.localizers.PinpointConfig;
import com.pedropathing.revhub.localizers.PinpointLocalizer;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;

public class Constants {

    // Starting values, worked out from DriveSubsystem. Replace with what the Mecanum tuner generates.
    // Pedro needs positive power to mean forward; DriveSubsystem drives forward with negative power,
    // so these are the opposite of the directions set there.
    public static MecanumConfig drivetrainConfig = new MecanumConfig(c -> {
        c.frontLeftName.set("LFD");
        c.frontRightName.set("RFD");
        c.backLeftName.set("LBD");
        c.backRightName.set("RBD");
        c.frontLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.frontRightDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backRightDirection.set(DcMotorSimple.Direction.FORWARD);
    });

    // Starting values, copied from OdometrySubsystem. Replace with what the Pinpoint tuner generates.
    public static PinpointConfig localizerConfig = new PinpointConfig(c -> {
        c.name.set("pinpoint");
        c.podType.set(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD);
        c.xPodOffset.set(-3.190764479749785);
        c.yPodOffset.set(-6.6334371491679995);
        c.xPodDirection.set(GoBildaPinpointDriver.EncoderDirection.FORWARD);
        c.yPodDirection.set(GoBildaPinpointDriver.EncoderDirection.REVERSED);
        c.globalDistanceUnit.set(DistanceUnit.INCH);
        c.offsetUnits.set(DistanceUnit.INCH);
    });

    // Generated by the Foresight tuner.
    public static ForesightConfig foresightConfig = new ForesightConfig(
            c -> {
                Controller primaryTranslationalForward = Controller.proportional(2.5232648466934604);
                Controller secondaryTranslationalForward = Controller.proportional(0.9322789379747852);
                Controller primaryTranslationalLateral = Controller.proportional(0.25887386771664495);
                Controller secondaryTranslationalLateral = Controller.proportional(0.09564697688415832);

                c.forwardTranslational.set(Controller.piecewise(secondaryTranslationalForward).put(2.5, primaryTranslationalForward));
                c.strafeTranslational.set(Controller.piecewise(secondaryTranslationalLateral).put(2.5, primaryTranslationalLateral));

                c.coast.set(Controller.proportionalFeedforward(0.017064876663109654));
                c.brake.set(Controller.proportionalFeedforward(0.014505145163643205));

                c.headingFeedback.set(Controller.proportional(3.825351991200836));
                c.headingBrakeCoefficients.set(Vector2D.cartesian(0.7935739157923506, -0.11305710332047533));

                c.linearBrakeCoefficients.set(Matrix.diag(0.04108987366434134, 0.0406094226748521));
                c.quadraticBrakeCoefficients.set(Matrix.diag(0.001441580280131409, 0.0013839467857555182));

                c.maxAchievableForwardVelocity.set(59.49103567646664);
                c.maxAchievableStrafeVelocity.set(50.57145509978714);
                c.naturalForwardDeceleration.set(29.95404601942078);
                c.naturalStrafeDeceleration.set(57.41288538508037);
            }
    );

    public static Follower create(HardwareMap h) {
        return new Follower(
                new PinpointLocalizer(h, localizerConfig),
                new Mecanum(h, drivetrainConfig),
                new Foresight(foresightConfig));
    }
}
